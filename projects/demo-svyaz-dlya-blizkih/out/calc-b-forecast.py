"""Прогноз варианта B по пяти строкам таблицы брифа, разрыв до цели, пилот.

Только арифметика. Исходные числа брифа M-01 (учебные): C-006, C-007, C-008, C-009, C-040,
ставка 500 руб. (C-020), ресурсы Q2 (C-024, C-025, C-043, C-069).
Параметры эффекта B, долей каналов и числа номеров — допущения (гипотезы), не данные.
"""

import math

# --- факты брифа: (план, оценка, без изменений, цель) ---
profit = (282, 275, 279, 285)  # млн руб.
active = (5000, 4000, 5000, 8000)
groups = (7500, 6500, 8000, 12000)
owners = (1000, 800, 1000, 2000)
activation = (50, 42, 45, 60)  # %
rate = 500
direct_cost_share = 0.20  # допущение

# --- допущения по сценариям эффекта B (низкий, базовый, высокий) ---
scen = {
    "низкий": {"act_pp": 0.0, "active_pp": 0.0, "extra_groups": 0, "saved_share": 0.00, "months_each": 2},
    "базовый": {"act_pp": 4.0, "active_pp": 3.0, "extra_groups": 400, "saved_share": 0.02, "months_each": 3},
    "высокий": {"act_pp": 8.0, "active_pp": 6.0, "extra_groups": 900, "saved_share": 0.04, "months_each": 4},
}
numbers_per_group = {"низкий": 2.0, "базовый": 2.0, "высокий": 2.5}  # в группе минимум 2 номера (C-012)

no_change_active_share = active[2] / groups[2] * 100  # 62.5 %

print("# Прогноз варианта B по пяти строкам таблицы брифа (учебные числа M-01)\n")
print("Допущения сценариев (не данные):")
print("- эффект B начинается с начала третьего квартала после пилота во втором (допущение, даты брифа относительные)")
print("- доля новых прямых расходов в доп. прибыли 20%")
print("- дополнительный номер даёт 500 руб. валовой прибыли за оплаченный месяц\n")

results = {}
for name, s in scen.items():
    n_per = numbers_per_group[name]
    extra_g = s["extra_groups"]
    months_attr = extra_g * n_per * s["months_each"]
    numbers_existing = groups[2] * 2  # минимум 2 номера в группе
    months_ret = numbers_existing * s["saved_share"] * s["months_each"]
    months = months_attr + months_ret
    extra_profit = months * rate * (1 - direct_cost_share) / 1e6
    p = profit[2] + extra_profit
    g = groups[2] + extra_g
    share = no_change_active_share + s["active_pp"]
    a = g * share / 100
    act = activation[2] + s["act_pp"]
    results[name] = dict(months=months, extra_profit=extra_profit, p=p, g=g, a=a, act=act, share=share)

print("## Таблица прогноза: значение при B и разрыв до цели")
print("| Показатель | цель | без изменений | B низкий | B базовый | B высокий | разрыв до цели при B базовом |")
print("|---|---|---|---|---|---|---|")
low, base, high = results["низкий"], results["базовый"], results["высокий"]
print(
    f"| Валовая прибыль, млн руб. | {profit[3]} | {profit[2]} | {low['p']:.1f} | {base['p']:.1f} | {high['p']:.1f} | "
    f"{profit[3] - base['p']:.1f} |"
)
print(
    f"| Активные группы за последний месяц | {active[3]} | {active[2]} | {low['a']:.0f} | {base['a']:.0f} | {high['a']:.0f} | "
    f"{active[3] - base['a']:.0f} |"
)
print(
    f"| Подключённые группы на конец года | {groups[3]} | {groups[2]} | {low['g']} | {base['g']} | {high['g']} | "
    f"{groups[3] - base['g']} |"
)
print(
    f"| Подключённые владельцы на конец года | {owners[3]} | {owners[2]} | {owners[2]} | {owners[2]} | {owners[2]} | "
    f"{owners[3] - owners[2]} (B владельцев не затрагивает) |"
)
print(
    f"| Активация за 14 дней, % | {activation[3]} | {activation[2]} | {low['act']:.0f} | {base['act']:.0f} | {high['act']:.0f} | "
    f"{activation[3] - base['act']:.0f} п.п. |"
)
print()

print("## Откуда прибыль (допущения)")
for name, r in results.items():
    print(f"- {name}: {r['months']:,.0f} доп. оплаченных номеро-месяцев → +{r['extra_profit']:.2f} млн руб. после прямых расходов".replace(",", " "))
needed = (profit[3] - profit[2]) * 1e6 / rate
print(f"- нужно по брифу: {needed:,.0f} номеро-месяцев (при ставке 500 без прямых расходов)".replace(",", " "))
print(f"- доля нужного, которую даёт B базовый: {base['months'] / needed:.0%}; высокий: {high['months'] / needed:.0%}\n")

# --- потолок вложений в пилот ---
print("## Предельная цена человеко-месяца при эффекте сценария")
print("| сценарий | доп. прибыль после прямых расходов, млн руб. | 3 чел.-мес. | 4,5 | 6 |")
print("|---|---|---|---|---|")
for name, r in results.items():
    cells = " | ".join(f"{r['extra_profit'] / e:.2f}" for e in (3.0, 4.5, 6.0))
    print(f"| {name} | {r['extra_profit']:.2f} | {cells} |")
print("- ячейки: млн руб. за человеко-месяц при окупаемости в плановом году; на низком сценарии пилот не окупается\n")

# --- привлечение: каналы ---
print("## Путь привлечения: каналы, допущения по долям")
share_ch = {"приложение": 40, "продажи": 25, "поддержка": 15, "рекомендации": 20}  # % новых групп, допущение
act_ch = {"приложение": 40, "продажи": 55, "поддержка": 50, "рекомендации": 45}  # % активации за 14 дней, допущение
print("| канал | доля новых групп, % | активация за 14 дней, % | вклад в взвешенную активацию, п.п. | прирост групп при B базовом (240 через приглашение) |")
print("|---|---|---|---|---|")
tot = 0.0
attr_groups = 240  # 60% от базового прироста 400 за счёт привлечения, допущение
for ch in share_ch:
    w = share_ch[ch] / 100 * act_ch[ch]
    tot += w
    print(f"| {ch} | {share_ch[ch]} | {act_ch[ch]} | {w:.1f} | {attr_groups * share_ch[ch] / 100:.0f} |")
print(f"- взвешенная активация по допущениям каналов: {tot:.1f}% (без изменений по брифу 45%; допущения подобраны близко к этой величине и проверяются на пилоте)\n")

gap_groups = groups[3] - groups[2]
pace_needed = gap_groups / 6
pace_now = (groups[2] - groups[1]) / 12
print("## Темп привлечения до цели 12 000 групп")
print(f"- разрыв до цели при «без изменений»: {gap_groups} групп")
print(f"- если закрывать за 6 месяцев: {pace_needed:.0f} групп в месяц")
print(f"- чистый прирост «без изменений» по брифу (6 500 → 8 000 за год): {pace_now:.0f} групп в месяц")
print(f"- нужно ускорение в {pace_needed / pace_now:.1f} раза\n")

# --- размер выборки пилота ---
z_a, z_b = 1.96, 0.8416


def n_arm(p1: float, d: float) -> float:
    pbar = p1 + d / 2
    return (z_a + z_b) ** 2 * 2 * pbar * (1 - pbar) / d**2


print("## Размер выборки пилота (двусторонний критерий, 5% ложного вывода, мощность 80%)")
print("| метрика | исходная доля | минимально важный эффект | групп на плечо | всего групп |")
print("|---|---|---|---|---|")
for label, p1, d in (
    ("доля активных групп за месяц (существующие группы)", 0.615, 0.05),
    ("доля активных групп за месяц (существующие группы)", 0.615, 0.03),
    ("активация за 14 дней (новые группы)", 0.45, 0.05),
):
    n = math.ceil(n_arm(p1, d))
    print(f"| {label} | {p1:.1%} | +{d * 100:.0f} п.п. | {n} | {2 * n} |")
print(f"- существующих подключённых групп на оценку базового года: {groups[1]}; 3 000 групп в пилоте это {3000 / groups[1]:.0%} базы")
print("- для активации новых групп темп создания групп в брифе не дан, поэтому активация новых групп не годится как основная метрика пилота второго квартала\n")

# --- ориентир на конец третьего года ---
g_year1_base = groups[2] + scen["базовый"]["extra_groups"]
trend = groups[2] / groups[1]  # 8000 / 6500
g_y3 = g_year1_base * trend**2
print("## Ориентир на конец третьего года (допущение)")
print(f"- рост «без изменений» от оценки базового года к плановому: {trend - 1:.1%}")
print(f"- подключённые группы в плановом году при B базовом: {g_year1_base}")
print(f"- продолжение темпа ещё два года: {g_year1_base} × {trend:.3f}² = {g_y3:,.0f}".replace(",", " "))
print(f"- доля доступных 100 тыс. домохозяйств: {g_y3 / 100000:.1%}")
g_y3_round = math.floor(g_y3 / 500) * 500
share_b = no_change_active_share + scen["базовый"]["active_pp"]
act_y3 = g_y3_round * share_b / 100
act_y3_round = math.floor(act_y3 / 500) * 500
print(f"- округление вниз до 500: {g_y3_round:,} подключённых групп ({g_y3_round / 100000:.1%} доступных)".replace(",", " "))
print(f"- активные группы при доле {share_b:.1f}%: {act_y3:,.0f}, округление вниз до 500: {act_y3_round:,}".replace(",", " "))
print(
    f"- ориентир на конец третьего года: не менее {g_y3_round:,} подключённых групп и {act_y3_round:,} активных групп".replace(",", " ")
)
print("- вывод: цель плана 12 000 групп при этой траектории достигается примерно на два года позже плана; это допущение, не прогноз брифа\n")

# --- порог обнаружения эффекта в пилоте на существующих группах ---
print("## Порог обнаружения эффекта пилота на 1 500 группах в плече")
n_pilot = 1500
p_act = 0.615
se = math.sqrt(2 * p_act * (1 - p_act) / n_pilot)
half = 1.96 * se
print(f"- стандартная ошибка разницы долей: {se * 100:.2f} п.п.")
print(f"- полуширина 95% интервала: ±{half * 100:.1f} п.п.")
print(f"- вывод: эффект ниже {half * 100:.1f} п.п. при таком размере пилота не отличить от нуля; базовый сценарий (+3 п.п.) пилот один не подтвердит")
print(f"- порог «стоп»: наблюдаемая разница меньше +2 п.п.; порог «расширять»: нижняя граница интервала не ниже 0, то есть наблюдаемая разница не меньше +{half * 100:.1f} п.п.; между ними продлить пилот")
