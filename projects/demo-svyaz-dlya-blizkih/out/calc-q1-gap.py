"""Q1: разрыв прибыли, потребность в оплаченных месяцах, предельные вложения.

Только арифметика. Входные числа — из брифа M-01 (учебные):
C-006 (279 и 285 млн), C-019/C-020 (6 млн, 500 руб., 12 000 месяцев),
C-008, C-009 (группы, владельцы), C-016, C-017 (доступный рынок),
C-024, C-025 (ресурсы Q2).
Всё, что ниже помечено «допущение», — не факт, а параметр для сценария.
"""

# --- условия брифа ---
profit_no_change = 279_000_000
profit_goal = 285_000_000
rate = 500  # руб. за дополнительный оплаченный месяц номера

groups_base_est = 6_500
groups_no_change = 8_000
groups_goal = 12_000
active_base_est = 4_000
active_no_change = 5_000
active_goal = 8_000
owners_base_est = 800
owners_no_change = 1_000
owners_goal = 2_000
avail_households = 100_000
avail_owners = 40_000

print("# Расчёт Q1 (учебные числа брифа M-01)\n")

# 1. Разрыв
gap = profit_goal - profit_no_change
months_needed = gap // rate
print("## 1. Разрыв и потребность в оплаченных месяцах")
print(f"- разрыв прибыли: {gap:,} руб.".replace(",", " "))
print(f"- нужно дополнительных оплаченных месяцев номера: {months_needed:,}".replace(",", " "))
print("- формула: (285 000 000 − 279 000 000) / 500\n")

# 2. Разрывы по показателям относительно «без изменений»
print("## 2. Разрывы цель против «без изменений» и охват")
gap_groups = groups_goal - groups_no_change
gap_owners = owners_goal - owners_no_change
gap_active = active_goal - active_no_change
print(f"- подключённые группы: {groups_goal} − {groups_no_change} = {gap_groups}")
print(f"- активные группы: {active_goal} − {active_no_change} = {gap_active}")
print(f"- подключённые владельцы: {owners_goal} − {owners_no_change} = {gap_owners}")
print(
    "- охват доступных домохозяйств (100 тыс.): оценка базового года "
    f"{groups_base_est / avail_households:.1%}, без изменений {groups_no_change / avail_households:.1%}, "
    f"цель {groups_goal / avail_households:.1%}"
)
print(
    "- охват доступных владельцев (40 тыс.): оценка базового года "
    f"{owners_base_est / avail_owners:.1%}, без изменений {owners_no_change / avail_owners:.1%}, "
    f"цель {owners_goal / avail_owners:.1%}"
)
print(
    "- доля активных среди подключённых: оценка "
    f"{active_base_est / groups_base_est:.1%}, без изменений {active_no_change / groups_no_change:.1%}, "
    f"цель {active_goal / groups_goal:.1%}"
)
print(
    "- доля цели, которую надо вырвать у «без изменений»: группы "
    f"{gap_groups / groups_goal:.1%} от цели; владельцы {gap_owners / owners_goal:.1%} от цели\n"
)
print(
    "- рост относительно базового года при «без изменений»: группы "
    f"{groups_no_change / groups_base_est - 1:.1%}, владельцы {owners_no_change / owners_base_est - 1:.1%}"
)
print(
    "- рост до цели относительно базового года: группы "
    f"{groups_goal / groups_base_est - 1:.1%}, владельцы {owners_goal / owners_base_est - 1:.1%}\n"
)

# 3. Сколько месяцев на единицу нужно, если разрыв закрывает только одна группа
print("## 3. Сколько оплаченных месяцев на каждую «добавочную единицу» закрывает разрыв 6 млн")
print("Допущение: разрыв закрывает только одна группа клиентов; каждая добавочная единица держит один дополнительный номер")
for share_of_year, label in ((1.0, "эффект весь год"), (0.5, "эффект полгода")):
    need_owner = months_needed / (gap_owners * share_of_year)
    need_group = months_needed / (gap_groups * share_of_year)
    print(
        f"- {label}: только владельцы — {need_owner:.1f} мес. на дополнительного владельца в год-эквиваленте; "
        f"только семьи — {need_group:.1f} мес. на дополнительную группу"
    )
print(
    "- пояснение: если к группе подключено больше одного дополнительного номера, нужное число месяцев на группу "
    "делится на число таких номеров (в брифе число номеров в группе не дано)\n"
)

# 4. Предельные вложения
print("## 4. Предельные вложения, которые может вернуть эффект (параметрический)")
print("Допущения: объём эффекта и доля новых прямых расходов в доп. прибыли не заданы в брифе, берём сценарии")
print("| доп. оплаченных месяцев | доп. прибыль, млн руб. | при прямых расходах 20% | при 40% |")
print("|---|---|---|---|")
for m in (12_000, 24_000, 48_000, 96_000):
    p = m * rate
    print(f"| {m:,} | {p / 1e6:.1f} | {p * 0.8 / 1e6:.1f} | {p * 0.6 / 1e6:.1f} |".replace(",", " "))
print()

# 5. Цена человеко-месяца
print("## 5. Предельная цена человеко-месяца при данных объёмах работ")
print("Допущение: объём работ 3 человеко-месяца разработки подтверждён; остальное (дизайн, аналитика, тестирование) не подтверждено, берём 3, 4,5 и 6")
print("| доп. прибыль, млн руб. (после прямых расходов) | 3 чел.-мес. | 4,5 чел.-мес. | 6 чел.-мес. |")
print("|---|---|---|---|")
for p_mln in (4.8, 9.6, 19.2, 38.4):
    cells = " | ".join(f"{p_mln / e:.2f}" for e in (3.0, 4.5, 6.0))
    print(f"| {p_mln} | {cells} |")
print("- ячейки: предельная цена одного человеко-месяца, млн руб. (если вложения должны окупиться за годовой горизонт эффекта)")
print("- 4,8 = 12 000 мес. × 500 руб. при прямых расходах 20% (минимум, закрывающий разрыв 6 млн); остальные строки — масштаб ×2, ×4, ×8")
