"""Польза -> метрика -> деньги для семейного сегмента при пути D -> разработка (B или E).
Числа брифа M-01: C-006 (группы 8 000 без изменений, 12 000 цель), C-011 (500 руб. за номеро-месяц), C-009 (разрыв 6 млн руб.).
Только арифметика. Результаты — прогнозы с допущениями, не факты.

Допущения (агента, не из брифа):
  m — номеро-месяцев дополнительной оплаты на каждую из новых групп за полный год;
  k — доля прироста групп до цели, которую можно приписать инициативе (бриф: не приписывать инициативе все подключения);
  f_plan — доля планового года, когда функция работает: пилот Q2, решение в конце Q2, разработка Q3, запуск с Q4 -> 0,25;
  во второй и третий год функция работает весь год, f = 1; эффект на новые группы за год повторяется.
"""

RATE = 500
GROUPS_ADD = 12_000 - 8_000
GAP_MLN = 6.0
F_PLAN = 0.25

scenarios = [
    ("осторожный", 1, 0.25),
    ("базовый", 2, 0.5),
    ("оптимистичный", 3, 1.0),
]

print("# Экономика пути D -> разработка: сценарии вклада, млн руб. валовой прибыли")
print()
print(f"Прирост групп до цели: {GROUPS_ADD}; ставка {RATE} руб. за номеро-месяц; запуск продукта с Q4 планового года (f={F_PLAN})")
print()
print("Формула: вклад за период = прирост групп × m × ставка × k × f / 1 000 000")
print()
print("| Сценарий | m | k | Плановый год | Полный год | 2 года (план + 1) | 3 года (план + 2) |")
print("|---|---|---|---|---|---|---|")
totals = {}
for name, m, k in scenarios:
    full = GROUPS_ADD * m * RATE * k / 1_000_000
    plan = full * F_PLAN
    two = plan + full
    three = plan + 2 * full
    totals[name] = (plan, full, two, three)
    print(f"| {name} | {m} | {k:.2f} | {plan:.2f} | {full:.2f} | {two:.2f} | {three:.2f} |")
print()
print("## Предельная сумма вложений")
print("Если вложения должны окупиться валовой прибылью за горизонт, сумма не должна превышать вклада за этот горизонт.")
for name, _, _ in scenarios:
    plan, full, two, three = totals[name]
    print(f"{name}: за 2 года не более {two:.2f} млн руб.; за 3 года не более {three:.2f} млн руб.")
print()
print("## Сколько плановый год закрывает из разрыва 6 млн руб.")
for name, _, _ in scenarios:
    plan = totals[name][0]
    print(f"{name}: {plan:.2f} млн руб. = {plan / GAP_MLN * 100:.0f} % разрыва")
print()
print("## Порог окупаемости: сколько номеро-месяцев на группу при k=0,5 нужно, чтобы вклад за год равнялся заданной сумме вложений")
for invest in (0.5, 1.0, 2.0, 3.0):
    m_need = invest * 1_000_000 / (GROUPS_ADD * RATE * 0.5)
    print(f"вложения {invest:.1f} млн руб. за полный год окупаются при m = {m_need:.2f} номеро-мес. на группу (k=0,5)")
