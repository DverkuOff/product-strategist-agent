"""Прогноз по пяти строкам таблицы брифа, ориентир третьего года, ресурсы пилота.
Числа брифа M-01: C-004, C-005, C-006, C-007, C-029 (колонки «без изменений» и «оценка базового года»).
Вклад инициативы: out/calc-economics.md (плановый год: осторожный 0,125, базовый 0,5, оптимистичный 1,5; полный год 0,5 / 2,0 / 6,0).
Только арифметика. Результаты — прогнозы и допущения агента.
"""

NO_CHANGE = {"profit": 279.0, "active": 5000, "connected": 8000, "owners": 1000, "activation": 45}
BASE_EST = {"profit": 275.0, "active": 4000, "connected": 6500, "owners": 800, "activation": 42}
PLAN_YEAR_CONTRIB = {"cautious": 0.125, "base": 0.5, "optimistic": 1.5}
FULL_YEAR_CONTRIB = {"cautious": 0.5, "base": 2.0, "optimistic": 6.0}

print("# Прогноз по пяти строкам таблицы брифа (конец планового года)")
print()
print("Допущения: основной сценарий — значения «без изменений» из брифа плюс базовый вклад услуги;")
print("менее благоприятный — сохраняется оценка базового года плюс осторожный вклад.")
print("Услуга запускается как продукт не раньше Q4 планового года, поэтому подключения и активность в плановый год вклад услуги не двигает выше погрешности (допущение).")
print()
print("| Показатель | Без изменений (бриф) | Оценка базового года | Основной сценарий | Менее благоприятный | Цель |")
print("|---|---|---|---|---|---|")
profit_main = NO_CHANGE["profit"] + PLAN_YEAR_CONTRIB["base"]
profit_low = BASE_EST["profit"] + PLAN_YEAR_CONTRIB["cautious"]
print(f"| Валовая прибыль, млн руб. | {NO_CHANGE['profit']:.0f} | {BASE_EST['profit']:.0f} | {profit_main:.1f} | {profit_low:.1f} | 285 |")
print(f"| Активные семейные группы | {NO_CHANGE['active']} | {BASE_EST['active']} | {NO_CHANGE['active']} | {BASE_EST['active']} | 8000 |")
print(f"| Подключённые семейные группы | {NO_CHANGE['connected']} | {BASE_EST['connected']} | {NO_CHANGE['connected']} | {BASE_EST['connected']} | 12000 |")
print(f"| Подключённые владельцы нескольких номеров | {NO_CHANGE['owners']} | {BASE_EST['owners']} | {NO_CHANGE['owners']} | {BASE_EST['owners']} | 2000 |")
print(f"| Доля активированных групп, % | {NO_CHANGE['activation']} | {BASE_EST['activation']} | {NO_CHANGE['activation']} | {BASE_EST['activation']} | 60 |")
print()
print(f"Недобор до 285 в основном сценарии: {285 - profit_main:.1f} млн руб.; в менее благоприятном: {285 - profit_low:.1f} млн руб.")
print()
print("## Ориентир на конец третьего года (годовая прибыль, млн руб.)")
print("Годовая прибыль = значение «без изменений» (279) + вклад семейной услуги за полный год (владельцы в третий год не учтены).")
for name, label in (("cautious", "осторожный"), ("base", "базовый"), ("optimistic", "оптимистичный")):
    print(f"{label}: {NO_CHANGE['profit'] + FULL_YEAR_CONTRIB[name]:.1f}")
print("Цель 285 достигается только в оптимистичном сценарии; ориентир по показателям — цели брифа (группы 12 000, активные 8 000, доля активированных 60 %),")
print("при условии, что пилот подтвердил эффект и принято решение о разработке.")
print()
print("## Ресурсы пилота (человеко-месяцы, оценка агента)")
roles = [
    ("руководитель направления (0,1 ставки, 6 месяцев)", 0.1 * 6),
    ("дизайнер (0,5 ставки, 3 месяца: тексты сообщений, приглашение, согласие)", 0.5 * 3),
    ("аналитик (0,5 ставки, 6 месяцев: данные, интервью, замеры)", 0.5 * 6),
    ("разработчики (подготовка данных; из 3 человеко-месяцев на Q2 берём не больше 1)", 1.0),
    ("специалист по проверке (1 человеко-месяц, пока не подтверждён)", 1.0),
]
total = 0.0
for name, hm in roles:
    print(f"- {name}: {hm:.1f}")
    total += hm
print(f"Итого около {total:.1f} человеко-месяца без труда службы поддержки (его оценить не из чего).")
print()
print("## Календарь (кварталы планового года)")
print("Q1 — подготовка (3 месяца), Q2 — пилот и решение (3 месяца), Q3 — разработка при положительном решении, Q4 — запуск продукта.")
print(f"До решения о расширении: {3 + 3} месяцев.")
