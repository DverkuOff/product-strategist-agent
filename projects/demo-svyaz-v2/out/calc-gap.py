"""Q1: какой сегмент способен закрыть разрыв до 285 млн руб. при учебных числах брифа M-01.

Исходные числа (все из брифа, C-004, C-006, C-007, C-009, C-010, C-011, C-012):
  разрыв 6 млн руб.; ставка 500 руб. за доп. оплаченный месяц номера;
  семейные группы на конец года: без изменений 8 000, цель 12 000;
  владельцы нескольких номеров: без изменений 1 000, цель 2 000.
Только арифметика. Результат: гипотезы, а не факты.
"""

GAP_RUB = 6_000_000
RATE_RUB = 500
FAMILY_NO_CHANGE = 8_000
FAMILY_GOAL = 12_000
OWNERS_NO_CHANGE = 1_000
OWNERS_GOAL = 2_000

months_needed = GAP_RUB / RATE_RUB
family_added = FAMILY_GOAL - FAMILY_NO_CHANGE
owners_added = OWNERS_GOAL - OWNERS_NO_CHANGE

print("# Расчёт Q1: нужный дополнительный объём и вклад сегментов")
print()
print("Формулы: месяцев = разрыв / ставка; прирост = цель - без изменений;")
print("нужно месяцев на единицу = месяцев / прирост.")
print()
print(f"Нужно дополнительных оплаченных месяцев: {months_needed:.0f} (6 000 000 / 500)")
print(f"Эквивалент в номеро-годах: {months_needed / 12:.0f}")
print()
print(f"Прирост подключённых семейных групп до цели: {family_added}")
print(f"Прирост подключённых владельцев до цели: {owners_added}")
print()
print("## Сколько доп. оплаченных месяцев на год нужно получить от каждой единицы прироста,")
print("## если закрывать весь разрыв одним сегментом")
print(f"Только семьи: {months_needed / family_added:.1f} мес. на группу")
print(f"Только владельцы: {months_needed / owners_added:.1f} мес. на владельца")
print()
print("## Если оба сегмента достигают цели и вклад на единицу одинаков")
total_added = family_added + owners_added
print(f"Всего прироста: {total_added}; нужно {months_needed / total_added:.1f} мес. на единицу")
print()
print("## Вклад при условных значениях (мес. на единицу прироста за год) и ставке 500 руб.")
print("мес/ед | семьи, млн руб. | владельцы, млн руб.")
for m in (1, 2, 3, 6, 12):
    fam = family_added * m * RATE_RUB / 1_000_000
    own = owners_added * m * RATE_RUB / 1_000_000
    print(f"{m:>6} | {fam:>15.2f} | {own:>19.2f}")
print()
print("Оговорки: единица прироста у семей — группа (в группе несколько номеров), у владельцев — владелец;")
print("сколько оплаченных месяцев даёт единица, бриф не говорит (нет данных об удержании) — это допущение.")
print("Прирост до цели включает всё, что случится за год, а не только эффект услуги (бриф просит не приписывать инициативе все подключения).")
