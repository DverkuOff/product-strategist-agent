"""Расчёты для сравнения вариантов (этап options). Числа брифа M-01: C-003, C-004, C-005, C-006, C-007, C-009, C-011.
Только арифметика. Результаты — гипотезы и прогнозы, не факты.
"""

RATE = 500
GAP_MLN = 6.0
GOAL = 285.0
BASE_EST = 275.0
BASE_PLAN = 282.0
NO_CHANGE = 279.0

FAM_AVAILABLE = 100_000
OWN_AVAILABLE = 40_000
FAM_NO_CHANGE, FAM_GOAL = 8_000, 12_000
OWN_NO_CHANGE, OWN_GOAL = 1_000, 2_000

print("# Расчёты к options.md")
print()
print("## 1. Цена бездействия")
print(f"Оценка базового года {BASE_EST:.0f} против плана {BASE_PLAN:.0f}: недобор {BASE_PLAN - BASE_EST:.0f} млн руб.")
print(f"Прогноз «без изменений» {NO_CHANGE:.0f} предполагает рост к оценке {BASE_EST:.0f}: +{NO_CHANGE - BASE_EST:.0f} млн руб.")
print(f"Недобор до цели {GOAL:.0f}: {GOAL - NO_CHANGE:.0f} млн руб. = {round((GOAL - NO_CHANGE) / GOAL * 100, 1)} % цели")
print(f"Если рост оценки базового года не повторится (прибыль остаётся {BASE_EST:.0f}), недобор до цели {GOAL - BASE_EST:.0f} млн руб.")
print()
print("## 2. Доля доступной базы, которую нужно подключить (единицы условно сопоставлены, бриф)")
print(f"Семьи: без изменений {FAM_NO_CHANGE / FAM_AVAILABLE * 100:.1f} %, цель {FAM_GOAL / FAM_AVAILABLE * 100:.1f} % доступных 100 тыс.")
print(f"Владельцы: без изменений {OWN_NO_CHANGE / OWN_AVAILABLE * 100:.1f} %, цель {OWN_GOAL / OWN_AVAILABLE * 100:.1f} % доступных 40 тыс.")
print()
print("## 3. Вклад в прибыль, млн руб./год = прирост × месяцев на единицу × 500 × доля, приписываемая инициативе (k)")
fam_add = FAM_GOAL - FAM_NO_CHANGE
own_add = OWN_GOAL - OWN_NO_CHANGE
print(f"Прирост до цели: семьи {fam_add}, владельцы {own_add}")
print()
print("Семьи (прирост 4 000 групп)")
print("мес/группа | k=25 % | k=50 % | k=100 %")
for m in (1, 2, 3):
    row = [fam_add * m * RATE * k / 1_000_000 for k in (0.25, 0.5, 1.0)]
    print(f"{m:>10} | {row[0]:>7.2f} | {row[1]:>7.2f} | {row[2]:>8.2f}")
print()
print("Владельцы (прирост 1 000)")
print("мес/влад. | k=25 % | k=50 % | k=100 %")
for m in (3, 6, 12):
    row = [own_add * m * RATE * k / 1_000_000 for k in (0.25, 0.5, 1.0)]
    print(f"{m:>9} | {row[0]:>7.2f} | {row[1]:>7.2f} | {row[2]:>8.2f}")
print()
print("Вывод по порядку величин: семьи при 3 мес. и k=100 % дают ровно разрыв (6,00);")
print("при k=50 % закрывают половину. Владельцы закрывают разрыв только при 12 мес. и k=100 %.")
print()
print("## 4. Срок запуска: доля планового года, в которую функция работает (f)")
print("Вклад умножается на f. Запуск с начала Q3 даёт f=0,5; с начала Q4 даёт f=0,25 (допущение о календаре: Q1-Q4 планового года).")
print("Семьи, 3 номеро-мес. на группу, прирост 4 000:")
print("f    | k=50 % | k=100 %")
for f in (1.0, 0.5, 0.25):
    row = [fam_add * 3 * RATE * k * f / 1_000_000 for k in (0.5, 1.0)]
    print(f"{f:<4} | {row[0]:>6.2f} | {row[1]:>7.2f}")
print("Владельцы, 12 номеро-мес. на владельца, прирост 1 000:")
print("f    | k=50 % | k=100 %")
for f in (1.0, 0.5, 0.25):
    row = [own_add * 12 * RATE * k * f / 1_000_000 for k in (0.5, 1.0)]
    print(f"{f:<4} | {row[0]:>6.2f} | {row[1]:>7.2f}")
print()
print("## 5. Единицы: ставка 500 руб. относится к одному номеру, поэтому месяцы выше — номеро-месяцы на единицу")
print("Нужно номеро-месяцев на единицу прироста при закрытии разрыва одним сегментом: семьи 3,0 на группу; владельцы 12,0 на владельца")
print("Если в группе в среднем n номеров, то на один номер группы нужно 3,0 / n; у владельца допущение: 2 номера в кабинете (минимум по определению подключения)")
for n in (2, 3, 5):
    print(f"  группа из {n} номеров: {3.0 / n:.1f} мес. на номер")
print(f"  владелец с 2 номерами: {12.0 / 2:.1f} мес. на номер")
print("Вывод: при любом числе номеров в группе от 2 до 5 нужное значение на номер у семей ниже, чем у владельцев; порядок вывода не меняется.")
print()
print("## 6. Мощность пилота: минимальный различимый эффект по активации при базе 45 % (значение «без изменений»)")
print("Двустороннее сравнение долей, уровень значимости 5 %, мощность 80 %; число групп на ветку n; требуемый эффект до цели: 15 п.п.")
Z = 1.96 + 0.8416
base = 0.45
for n in (100, 150, 200, 300):
    d = 0.005
    while d < 0.5:
        p2 = base + d
        need = Z * Z * (base * (1 - base) + p2 * (1 - p2)) / (d * d)
        if need <= n:
            break
        d += 0.005
    print(f"  n={n} групп на ветку: минимальный различимый эффект около {d * 100:.1f} п.п.")
print("Пример брифа: 600 групп за шесть недель (пример, не данные): две ветки по 300, три ветки по 200, четыре ветки по 150.")
print("Вывод: при трёх ветках различим эффект порядка 14 п.п., то есть почти весь путь от 45 % до 60 % (15 п.п.): более мелкий эффект пилот не увидит.")
